-- Duel Arena: base commune accessible sans compte, conformément au choix d'accès par lien.
-- ATTENTION : toute personne ayant le lien peut lire, ajouter, modifier et supprimer les données.

create table if not exists public.players (
  id integer primary key check (id between 1 and 4),
  name text not null check (char_length(trim(name)) between 1 and 35)
);

insert into public.players (id, name) values
  (1, 'Joueur 1'), (2, 'Joueur 2'), (3, 'Joueur 3'), (4, 'Joueur 4')
on conflict (id) do nothing;

create table if not exists public.duels (
  id bigint generated by default as identity primary key,
  winner_id integer not null references public.players(id),
  loser_id integer not null references public.players(id),
  winner_deck text not null check (char_length(trim(winner_deck)) between 1 and 60),
  loser_deck text not null check (char_length(trim(loser_deck)) between 1 and 60),
  duel_date date not null default current_date,
  note text not null default '' check (char_length(note) <= 120),
  created_at timestamptz not null default now(),
  constraint different_players check (winner_id <> loser_id)
);

alter table public.players enable row level security;
alter table public.duels enable row level security;

-- Policies ouvertes: nécessaires au mode "n'importe qui avec le lien".
drop policy if exists "public read players" on public.players;
drop policy if exists "public insert players" on public.players;
drop policy if exists "public update players" on public.players;
drop policy if exists "public delete players" on public.players;
create policy "public read players" on public.players for select to anon, authenticated using (true);
create policy "public insert players" on public.players for insert to anon, authenticated with check (true);
create policy "public update players" on public.players for update to anon, authenticated using (true) with check (true);
create policy "public delete players" on public.players for delete to anon, authenticated using (true);

drop policy if exists "public read duels" on public.duels;
drop policy if exists "public insert duels" on public.duels;
drop policy if exists "public update duels" on public.duels;
drop policy if exists "public delete duels" on public.duels;
create policy "public read duels" on public.duels for select to anon, authenticated using (true);
create policy "public insert duels" on public.duels for insert to anon, authenticated with check (true);
create policy "public update duels" on public.duels for update to anon, authenticated using (true) with check (true);
create policy "public delete duels" on public.duels for delete to anon, authenticated using (true);

grant select, insert, update, delete on public.players to anon, authenticated;
grant select, insert, update, delete on public.duels to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

