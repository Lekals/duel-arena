-- Duel Arena: base commune accessible sans compte, conformément au choix d'accès par lien.
-- ATTENTION : toute personne ayant le lien peut lire, ajouter, modifier et supprimer les données.

create table if not exists public.players (
  id integer primary key check (id between 1 and 4),
  name text not null check (char_length(trim(name)) between 1 and 35)
);

insert into public.players (id, name) values
  (1, 'Joueur 1'), (2, 'Joueur 2'), (3, 'Joueur 3'), (4, 'Joueur 4')
on conflict (id) do nothing;


create table if not exists public.decks (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 60),
  created_at timestamptz not null default now()
);
create unique index if not exists decks_name_lower_unique on public.decks (lower(trim(name)));

insert into public.decks (name) values
  ('Trains'), ('Sky Striker'), ('Branded'), ('Branded/Dracotail'), ('Blue-Eyes'),
  ('Blue-Eyes/Dracotail'), ('Blitzclique'), ('Sacred Beast'), ('Blitzclique/Ryzel'),
  ('Lunalight'), ('Orcust'), ('VS/K9')
on conflict do nothing;

create table if not exists public.seasons (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 40),
  start_date date not null unique,
  created_at timestamptz not null default now()
);

alter table public.seasons enable row level security;
drop policy if exists "public read seasons" on public.seasons;
drop policy if exists "public insert seasons" on public.seasons;
drop policy if exists "public delete seasons" on public.seasons;
create policy "public read seasons" on public.seasons for select to anon, authenticated using (true);
create policy "public insert seasons" on public.seasons for insert to anon, authenticated with check (true);
create policy "public delete seasons" on public.seasons for delete to anon, authenticated using (true);

create table if not exists public.duels (
  id bigint generated by default as identity primary key,
  winner_id integer not null references public.players(id),
  loser_id integer not null references public.players(id),
  winner_deck text not null check (char_length(trim(winner_deck)) between 1 and 60),
  loser_deck text not null check (char_length(trim(loser_deck)) between 1 and 60),
  duel_date date not null default current_date,
  note text not null default '' check (char_length(note) <= 120),
  winner_ydke text check (char_length(winner_ydke) <= 1000),
  loser_ydke text check (char_length(loser_ydke) <= 1000),
  winner_went_first boolean,
  created_at timestamptz not null default now(),
  constraint different_players check (winner_id <> loser_id)
);

alter table public.players enable row level security;
alter table public.duels enable row level security;

alter table public.decks enable row level security;
drop policy if exists "public read decks" on public.decks;
drop policy if exists "public insert decks" on public.decks;
drop policy if exists "public delete decks" on public.decks;
create policy "public read decks" on public.decks for select to anon, authenticated using (true);
create policy "public insert decks" on public.decks for insert to anon, authenticated with check (true);
create policy "public delete decks" on public.decks for delete to anon, authenticated using (true);


