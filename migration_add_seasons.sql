-- Duel Arena: saisons partagées (une saison court de sa date de début jusqu'à la veille de la suivante).
create table if not exists public.seasons (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 40),
  start_date date not null unique,
  created_at timestamptz not null default now()
);

alter table public.seasons enable row level security;
drop policy if exists "public read seasons" on public.seasons;
drop policy if exists "public insert seasons" on public.seasons;
drop policy if exists "public delete seasons" on public.seasons;
create policy "public read seasons" on public.seasons for select to anon, authenticated using (true);
create policy "public insert seasons" on public.seasons for insert to anon, authenticated with check (true);
create policy "public delete seasons" on public.seasons for delete to anon, authenticated using (true);

grant select, insert, delete on public.seasons to anon, authenticated;
grant usage, select on sequence public.seasons_id_seq to anon, authenticated;
do $$
begin
  alter publication supabase_realtime add table public.seasons;
exception when duplicate_object then null;
end $$;
