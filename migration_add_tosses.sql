-- Duel Arena: tirages au sort (pile ou face / dés) faits avant un duel, pour les stats de chance.
-- winner_id est null quand les dés tombent sur le même chiffre ; roll1 / roll2 sont null pour pile ou face.
create table if not exists public.tosses (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('coin', 'dice')),
  duel_date date not null default current_date,
  player1_id integer not null references public.players(id),
  player2_id integer not null references public.players(id),
  roll1 smallint check (roll1 between 1 and 6),
  roll2 smallint check (roll2 between 1 and 6),
  winner_id integer references public.players(id),
  created_at timestamptz not null default now(),
  constraint toss_different_players check (player1_id <> player2_id)
);

alter table public.tosses enable row level security;
drop policy if exists "public read tosses" on public.tosses;
drop policy if exists "public insert tosses" on public.tosses;
create policy "public read tosses" on public.tosses for select to anon, authenticated using (true);
create policy "public insert tosses" on public.tosses for insert to anon, authenticated with check (true);

grant select, insert on public.tosses to anon, authenticated;
grant usage, select on sequence public.tosses_id_seq to anon, authenticated;
do $$
begin
  alter publication supabase_realtime add table public.tosses;
exception when duplicate_object then null;
end $$;
